const YELLOW: &str = "1;38;5;221";
const CYAN: &str = "1;38;5;87";
const PEACH: &str = "1;38;5;216";

const ALL_BANNER: &[(&str, usize)] = &[
    (BANNER1, 33),
    (BANNER2, 45),
    (BANNER3, 41),
    (BANNER4, 30),
];

fn paint(text: &str, code: &str) -> String {
    format!("\x1b[{}m{}\x1b[0m", code, text)
}

pub fn print_banner() {
    if !std::io::stdout().is_terminal() {
        return;
    }

    let (art, split) = ALL_BANNER.choose(&mut rand::rng()).unwrap();

    println!();
    for line in art.lines() {
        if line.trim().is_empty() {
            continue;
        }
        let line = line.trim_end();
        let tor: String = line.chars().take(*split).collect();
        let link: String = line.chars().skip(*split).collect();
        println!("{}{}", paint(&tor, YELLOW), paint(&link, CYAN));
    }
    println!();
    println!("{} \n \n", paint("  Finder · search Ahmia, check onion status over Tor", PEACH));
}